const storageKey = "atlas-language";
let currentLang = localStorage.getItem(storageKey) || "en";

function getPageScope() {
    return document.documentElement.getAttribute("data-page") || "";
}

function getTranslatedValue(lang, key) {
    const scopedKey = getPageScope() ? `${getPageScope()}.${key}` : "";

    if (scopedKey && translations[lang][scopedKey]) {
        return translations[lang][scopedKey];
    }

    return translations[lang][key];
}

function applyTranslation(lang) {
    document.documentElement.lang = lang;
    const pageTitle = getTranslatedValue(lang, "page.title");
    if (pageTitle) {
        document.title = pageTitle;
    }

    const metaDescription = document.querySelector('meta[name="description"]');
    if (metaDescription) {
        const metaDescriptionValue = getTranslatedValue(lang, "meta.description");
        if (metaDescriptionValue) {
            metaDescription.setAttribute("content", metaDescriptionValue);
        }
    }

    const canonicalLink = document.querySelector('link[rel="canonical"]');
    if (canonicalLink && !getPageScope()) {
        canonicalLink.setAttribute("href", "https://atlassettravel.com/");
    }

    const ogTitle = document.querySelector('meta[property="og:title"]');
    const ogDescription = document.querySelector('meta[property="og:description"]');
    const twitterTitle = document.querySelector('meta[name="twitter:title"]');
    const twitterDescription = document.querySelector('meta[name="twitter:description"]');
    const ogLocale = document.querySelector('meta[property="og:locale"]');

    if (ogTitle) {
        const ogTitleValue = getTranslatedValue(lang, "og.title") || (lang === "en" ? "Atlas Set | Luxury Travel Design" : "Atlas Set | Diseño de Viajes de Lujo");
        ogTitle.setAttribute("content", ogTitleValue);
    }
    if (ogDescription) {
        const ogDescriptionValue = getTranslatedValue(lang, "og.description") || (lang === "en"
            ? "Luxury travel design and personalized experiences for resorts, cruises, Europe tours, and bespoke journeys."
            : "Diseño de viajes de lujo y experiencias personalizadas para resorts, cruceros, tours por Europa y viajes a medida.");
        ogDescription.setAttribute("content", ogDescriptionValue);
    }
    if (twitterTitle) {
        const twitterTitleValue = getTranslatedValue(lang, "twitter.title") || (lang === "en" ? "Atlas Set | Luxury Travel Design" : "Atlas Set | Diseño de Viajes de Lujo");
        twitterTitle.setAttribute("content", twitterTitleValue);
    }
    if (twitterDescription) {
        const twitterDescriptionValue = getTranslatedValue(lang, "twitter.description") || (lang === "en"
            ? "Luxury travel design and personalized experiences for resorts, cruises, Europe tours, and bespoke journeys."
            : "Diseño de viajes de lujo y experiencias personalizadas para resorts, cruceros, tours por Europa y viajes a medida.");
        twitterDescription.setAttribute("content", twitterDescriptionValue);
    }
    if (ogLocale) {
        ogLocale.setAttribute("content", lang === "en" ? "en_US" : "es_ES");
    }

    document.querySelectorAll("[data-lang]").forEach((element) => {
        const key = element.getAttribute("data-lang");
        const value = getTranslatedValue(lang, key);

        if (!value) {
            return;
        }

        if (element.getAttribute("data-lang-type") === "placeholder") {
            element.setAttribute("placeholder", value);
        } else if (element.getAttribute("data-lang-type") === "aria-label") {
            element.setAttribute("aria-label", value);
        } else if (element.getAttribute("data-lang-type") === "html") {
            element.innerHTML = value;
        } else {
            element.textContent = value;
        }
    });

    const toggle = document.getElementById("language-toggle");
    if (toggle) {
        toggle.textContent = lang === "en" ? "ES" : "EN";
        toggle.setAttribute("aria-label", lang === "en" ? "Switch to Spanish" : "Switch to English");
    }

    localStorage.setItem(storageKey, lang);
    currentLang = lang;
}

function initReveal() {
    const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    if (prefersReducedMotion) {
        document.querySelectorAll(".reveal").forEach((element) => element.classList.add("is-visible"));
        return;
    }

    const revealTargets = document.querySelectorAll(
        ".hero-content, section, .method-card, .why-card, .experience-card, .trending-card, .final-cta-content, .contact-section .container, .contact-form"
    );

    revealTargets.forEach((element, index) => {
        element.classList.add("reveal");
        element.style.transitionDelay = `${Math.min(index * 70, 260)}ms`;
    });

    if ("IntersectionObserver" in window) {
        const observer = new IntersectionObserver(
            (entries) => {
                entries.forEach((entry) => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add("is-visible");
                        observer.unobserve(entry.target);
                    }
                });
            },
            {
                threshold: 0.16,
                rootMargin: "0px 0px -30px 0px"
            }
        );

        revealTargets.forEach((element) => observer.observe(element));
    } else {
        revealTargets.forEach((element) => element.classList.add("is-visible"));
    }
}

function initMobileWhatsAppVisibility() {
    const whatsapp = document.querySelector(".whatsapp-float");
    const hero = document.querySelector(".destination-hero");

    if (!whatsapp || !hero || !("IntersectionObserver" in window)) {
        return;
    }

    const mobileViewport = window.matchMedia("(max-width: 600px)");
    const observer = new IntersectionObserver(([entry]) => {
        whatsapp.classList.toggle("is-hidden-over-hero", mobileViewport.matches && entry.isIntersecting);
    });

    observer.observe(hero);
}

document.addEventListener("DOMContentLoaded", () => {
    applyTranslation(currentLang);
    initReveal();
    initMobileWhatsAppVisibility();

    const toggle = document.getElementById("language-toggle");
    if (toggle) {
        toggle.addEventListener("click", () => {
            applyTranslation(currentLang === "en" ? "es" : "en");
        });
    }

    const menuToggle = document.getElementById("menu-toggle");
    const header = document.querySelector(".header");

    const closeMobileMenu = () => {
        if (header) {
            header.classList.remove("is-open");
        }
        if (menuToggle) {
            menuToggle.setAttribute("aria-expanded", "false");
        }
    };

    const openMobileMenu = () => {
        if (header) {
            header.classList.toggle("is-open");
        }
        if (menuToggle) {
            const expanded = header?.classList.contains("is-open") ? "true" : "false";
            menuToggle.setAttribute("aria-expanded", expanded);
        }
    };

    if (menuToggle) {
        menuToggle.addEventListener("click", openMobileMenu);
    }

    document.querySelectorAll(".site-nav a, .right-menu a, .right-menu button").forEach((control) => {
        control.addEventListener("click", (event) => {
            const href = control.getAttribute("href");
            const target = href?.startsWith("#") ? document.querySelector(href) : null;

            closeMobileMenu();

            if (!target || window.innerWidth > 768) {
                return;
            }

            event.preventDefault();
            const fontsReady = document.fonts?.ready || Promise.resolve();

            fontsReady.then(() => window.requestAnimationFrame(() => {
                const root = document.documentElement;
                const previousScrollBehavior = root.style.scrollBehavior;
                const positionTarget = () => {
                    const scrollPadding = Number.parseFloat(getComputedStyle(root).scrollPaddingTop) || 0;
                    const targetTop = target.getBoundingClientRect().top + window.scrollY - scrollPadding;

                    window.scrollTo(0, targetTop);
                };

                root.style.scrollBehavior = "auto";
                positionTarget();
                window.history.pushState(null, "", href);
                window.requestAnimationFrame(() => {
                    positionTarget();
                    window.setTimeout(() => {
                        positionTarget();
                        root.style.scrollBehavior = previousScrollBehavior;
                    }, 150);
                });
            }));
        });
    });

    window.addEventListener("resize", () => {
        if (window.innerWidth > 768) {
            closeMobileMenu();
        }
    });
});










